def _slug(puzzle: Puzzle, index: int) -> str:
    return f"{index:02d}-{puzzle.theme}"


def _write_puzzle(puzzle: Puzzle, out: Path, index: int) -> tuple[Path, Path]:
    stem = _slug(puzzle, index)
    jpath = out / f"{stem}.json"
    mpath = out / f"{stem}.md"
    jpath.write_text(json.dumps(puzzle.to_json(), indent=2) + "\n", encoding="utf-8")
    mpath.write_text(to_markdown(puzzle, trace=True) + "\n", encoding="utf-8")
    return jpath, mpath


def _load(path: Path) -> Puzzle:
    return Puzzle.from_json(json.loads(path.read_text(encoding="utf-8")))


def cmd_gen(args: argparse.Namespace) -> int:
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    curve = None
    if args.difficulty:
        curve = [args.difficulty] * args.count
    print(
        f"generating {args.count} puzzles "
        f"({args.difficulty or 'ramp: ' + ', '.join(f'{n}x{p}' for p, n in RAMP)}), "
        f"seed {args.seed}"
    )
    puzzles = generate_many(
        count=args.count,
        seed=args.seed,
        curve=curve,
        theme=args.theme,
    )
    index_lines = [
        "# Puzzle set",
        "",
        f"{len(puzzles)} puzzles, seed `{args.seed}`, generated by logicgrid "
        f"{__version__}.",
        "",
        "Every puzzle below has been re-verified from its clues alone: exactly one",
        "solution, reachable without guessing unless the profile allows it.",
        "",
        "| # | Puzzle | Profile | Rating | Grid | Clues | Hardest technique |",
        "|---|--------|---------|--------|------|-------|-------------------|",
    ]
    for i, puzzle in enumerate(puzzles, start=1):
        jpath, mpath = _write_puzzle(puzzle, out, i)
        tech = puzzle.report.max_technique if puzzle.report else "?"
        index_lines.append(
            f"| {i} | [{puzzle.title}]({mpath.name}) | {puzzle.profile} | "
            f"{puzzle.rating}/7 | {len(puzzle.schema.categories)}x{puzzle.size} | "
            f"{len(puzzle.clues)} | {tech} |"
        )
        if args.verbose:
            print(
                f"  {i:2d}. r={puzzle.rating} {puzzle.profile:9s} "
                f"{len(puzzle.schema.categories)}x{puzzle.size} "
                f"clues={len(puzzle.clues):2d} {puzzle.theme}"
            )
    (out / "index.md").write_text("\n".join(index_lines) + "\n", encoding="utf-8")

    by_rating: dict[int, int] = {}
    for p in puzzles:
        by_rating[p.rating] = by_rating.get(p.rating, 0) + 1
    spread = ", ".join(f"{r}/7:{n}" for r, n in sorted(by_rating.items()))
    print(f"wrote {len(puzzles)} puzzles to {out}/  (ratings {spread})")
    print(f"index: {out / 'index.md'}")
    return 0


def cmd_show(args: argparse.Namespace) -> int:
    puzzle = _load(Path(args.path))
    if args.markdown:
        print(to_markdown(puzzle, solution=not args.hide_solution, trace=args.trace))
    else:
        print(to_text(puzzle, solution=not args.hide_solution))
        if args.trace:
            report = human_solve(puzzle.schema, puzzle.clues)
            print("\nWALKTHROUGH\n-----------")
            for i, step in enumerate(report.trace, start=1):
                print(f"{i:3d}. {step.describe(puzzle.schema)}")
    return 0


def cmd_solve(args: argparse.Namespace) -> int:
    puzzle = _load(Path(args.path))
    try:
        puzzle.verify()
    except PuzzleError as exc:
        print(f"VERIFY FAILED: {exc}", file=sys.stderr)
        return 1
    report = human_solve(puzzle.schema, puzzle.clues)
    print(f"{puzzle.title}")
    print(f"  uniqueness : exactly one solution, matching the recorded answer")
    print(f"  by hand    : {report.summary()}")
    print(f"  rating     : {puzzle.rating}/7 (score {puzzle.score})")
    if report.solution != puzzle.solution:
        print("  WARNING: hand solve disagrees with the recorded solution")
        return 1
    return 0


def cmd_stats(args: argparse.Namespace) -> int:
    paths = sorted(Path(args.path).glob("*.json"))
    if not paths:
        print(f"no puzzles found in {args.path}", file=sys.stderr)
        return 1
    rows = []
    bad = 0
    for path in paths:
        puzzle = _load(path)
        try:
            puzzle.verify()
            ok = "ok"
        except PuzzleError as exc:
            ok = f"BAD: {exc}"
            bad += 1
        report = human_solve(puzzle.schema, puzzle.clues)
        rows.append((path.name, puzzle, report, ok))

    print(f"{'file':28s} {'prof':9s} {'r':>3s} {'grid':>6s} {'clues':>5s} {'atoms':>5s} {'technique':12s} check")
    for name, puzzle, report, ok in rows:
        print(
            f"{name:28s} {puzzle.profile:9s} {puzzle.rating:3d} "
            f"{len(puzzle.schema.categories)}x{puzzle.size:<4d} "
            f"{len(puzzle.clues):5d} {len(puzzle.atoms()):5d} "
            f"{report.max_technique:12s} {ok}"
        )
    ratings = [p.rating for _, p, _, _ in rows]
    print(
        f"\n{len(rows)} puzzles, ratings {min(ratings)}-{max(ratings)}, "
        f"{len(rows) - bad}/{len(rows)} verified"
    )
    return 1 if bad else 0


def cmd_themes(args: argparse.Namespace) -> int:
    print(f"{'slug':14s} {'spine':10s} {'cats':>4s} {'items':>5s}  title")
    for theme in THEMES:
        print(
            f"{theme.slug:14s} {theme.spine.name:10s} "
            f"{theme.max_categories():4d} {theme.max_items():5d}  {theme.title}"
        )
    print(f"\n{len(THEMES)} themes")
    return 0


def cmd_narrate(args: argparse.Namespace) -> int:
    from .llm import Client, DryRunClient, ModelConfig
    from .narrate import build_request, canonical_narrative
    from .verify import roundtrip

    paths = sorted(Path(args.path).glob("*.json")) if Path(args.path).is_dir() else [Path(args.path)]
    if args.limit:
        paths = paths[: args.limit]
    out = Path(args.out) if args.out else Path(args.path if Path(args.path).is_dir() else ".")
    out.mkdir(parents=True, exist_ok=True)

    if args.dry_run:
        print(f"DRY RUN -- assembling prompts for {len(paths)} puzzles, no API calls\n")
        from .extract import build_request as extract_request

        CHARS_PER_TOKEN = 3.6  # rough, and only used for an order-of-magnitude
        narrator_tokens = 0.0
        extractor_tokens = 0.0
        for path in paths:
            puzzle = _load(path)
            request = build_request(puzzle)
            narrator_tokens += (len(request.system) + len(request.user)) / CHARS_PER_TOKEN
            # The real extractor reads the narration; the canonical rendering is
            # the closest stand-in available before any call is made.
            control = canonical_narrative(puzzle)
            ereq = extract_request(control.to_text())
            extractor_tokens += (
                args.readers * (len(ereq.system) + len(ereq.user)) / CHARS_PER_TOKEN
            )
            print(
                f"  {path.name}: {len(puzzle.clues)} clues, narrator prompt "
                f"~{len(request.user) / CHARS_PER_TOKEN:,.0f} tok, "
                f"each reader ~{len(ereq.user) / CHARS_PER_TOKEN:,.0f} tok"
            )
        if args.show:
            puzzle = _load(paths[0])
            request = build_request(puzzle)
            for label, body in (
                ("NARRATOR SYSTEM PROMPT", request.system),
                ("NARRATOR USER PROMPT (first puzzle)", request.user),
                ("EXTRACTOR SYSTEM PROMPT", extract_request("").system),
            ):
                print("\n" + "=" * 72 + f"\n{label}\n" + "=" * 72)
                print(body)

        calls = len(paths) * (1 + args.readers)
        total_in = narrator_tokens + extractor_tokens
        print(
            f"\n{len(paths)} puzzles x (1 narration + {args.readers} readings) "
            f"= {calls} calls"
        )
        print(
            f"input tokens: ~{narrator_tokens:,.0f} narration + "
            f"~{extractor_tokens:,.0f} reading = ~{total_in:,.0f} "
            f"(output not included; retries would add more)"
        )
        print(
            "set ANTHROPIC_API_KEY and add --no-dry-run to run it for real; "
            "llm.complete_batch halves the cost if you can wait."
        )
        return 0

    narrator = ModelConfig(model=args.narrator_model, effort=args.effort)
    extractor = ModelConfig(model=args.extractor_model, effort=args.effort)
    client = Client(config=narrator)
    print(
        f"narrating {len(paths)} puzzles with {narrator.describe()}, "
        f"{args.readers} readers on {extractor.describe()}"
    )

    results = []
    failures = 0
    for path in paths:
        puzzle = _load(path)
        result = roundtrip(
            puzzle,
            client,
            readers=args.readers,
            required=args.required,
            max_attempts=args.max_attempts,
            narrator_config=narrator,
            extractor_config=extractor,
            require_exact_ir=args.exact,
            on_attempt=lambda r: print(f"  {path.name}: {r.summary()}"),
        )
        results.append(result)
        stem = path.stem
        (out / f"{stem}.narrative.md").write_text(
            result.narrative.to_markdown() + "\n", encoding="utf-8"
        )
        (out / f"{stem}.roundtrip.json").write_text(
            json.dumps(result.to_json(), indent=2) + "\n", encoding="utf-8"
        )
        if result.passed:
            # Publish the shippable form too, in the shape
            # scripts/build_content_repo.py reads: narratives/<stem>.json,
            # carrying the pid so a narrative can never be paired with the
            # wrong puzzle after a reseed.
            #
            # Without this the API path verified narratives and then wrote
            # them somewhere nothing ships from, while the file-driven path in
            # scripts/narrative_batch.py published properly. Two routes to the
            # same place, one of which quietly did not arrive.
            publish = Path("narratives")
            publish.mkdir(parents=True, exist_ok=True)
            (publish / f"{stem}.json").write_text(
                json.dumps(
                    {**result.narrative.to_json(), "verdict": result.verdict},
                    indent=2,
                )
                + "\n",
                encoding="utf-8",
            )
        else:
            failures += 1
            print(f"  {path.name}: FAILED after {args.max_attempts} attempts")

    print(f"\n{len(results) - failures}/{len(results)} narratives verified")
    print(f"usage: {client.usage.summary(narrator.model)}")
    return 1 if failures else 0


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(
        prog="logicgrid",
        description="Generate and verify Penny Dell-style logic grid puzzles.",
    )
    ap.add_argument("--version", action="version", version=f"logicgrid {__version__}")
    sub = ap.add_subparsers(dest="command", required=True)

    g = sub.add_parser("gen", help="generate a set of puzzles")
    g.add_argument("--count", type=int, default=50)
    g.add_argument("--seed", type=int, default=20261118)
    g.add_argument("--out", default="puzzles")
    g.add_argument(
        "--difficulty",
        choices=sorted(PROFILES),
        help="use one profile for every puzzle instead of the ramp",
    )
    g.add_argument("--theme", help="restrict to one theme slug")
    g.add_argument("-v", "--verbose", action="store_true")
    g.set_defaults(func=cmd_gen)

    s = sub.add_parser("show", help="print a puzzle")
    s.add_argument("path")
    s.add_argument("--markdown", action="store_true")
    s.add_argument("--trace", action="store_true", help="include the deduction walkthrough")
    s.add_argument("--hide-solution", action="store_true")
    s.set_defaults(func=cmd_show)

    v = sub.add_parser("solve", help="re-verify and hand-solve one puzzle")
    v.add_argument("path")
    v.set_defaults(func=cmd_solve)

    st = sub.add_parser("stats", help="verify and summarise a puzzle folder")
    st.add_argument("path", nargs="?", default="puzzles")
    st.set_defaults(func=cmd_stats)

    t = sub.add_parser("themes", help="list the theme packs")
    t.set_defaults(func=cmd_themes)

    n = sub.add_parser("narrate", help="narrate puzzles and verify the round trip")
    n.add_argument("path", nargs="?", default="puzzles")
    n.add_argument("--out", help="where to write narratives (default: alongside)")
    n.add_argument("--readers", type=int, default=3, help="independent extractors")
    n.add_argument("--required", type=int, default=3, help="readers that must agree")
    n.add_argument("--max-attempts", type=int, default=3)
    n.add_argument("--limit", type=int, help="only the first N puzzles")
    n.add_argument("--narrator-model", default="claude-opus-5-5")
    n.add_argument("--extractor-model", default="claude-opus-5-5")
    n.add_argument("--effort", default="high", choices=["low", "medium", "high", "xhigh", "max"])
    n.add_argument(
        "--exact",
        action="store_true",
        help="require every reader to match the clue set atom for atom",
    )
    n.add_argument("--dry-run", dest="dry_run", action="store_true", default=True)
    n.add_argument("--no-dry-run", dest="dry_run", action="store_false")
    n.add_argument("--show", action="store_true", help="with --dry-run, print a full prompt")
    n.set_defaults(func=cmd_narrate)

    return ap


def main(argv: Sequence[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        return args.func(args)
    except PuzzleError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:  # pragma: no cover
        return 130


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
